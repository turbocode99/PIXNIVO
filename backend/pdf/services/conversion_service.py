class ConversionService:
    @staticmethod
    def pdf_to_docx(pdf_bytes: bytes) -> bytes:
        if not PdfReader:
            raise RuntimeError("pypdf is not installed")
        if not Document:
            raise RuntimeError("python-docx is not installed")

        reader = PdfReader(io.BytesIO(pdf_bytes))
        doc = Document()

        # Add Header Title
        title_p = doc.add_paragraph()
        title_run = title_p.add_run("Converted Document")
        title_run.font.size = Pt(20)
        title_run.font.bold = True
        title_run.font.color.rgb = RGBColor(0xCF, 0x4A, 0x0C) # Pixnivo Brand
        doc.add_paragraph("Generated by Pixnivo PDF Tools Suite — 100% Free & Open-Source")
        doc.add_paragraph().paragraph_format.space_after = Pt(12)

        for page_num, page in enumerate(reader.pages, start=1):
            text = page.extract_text() or ""
            lines = text.splitlines()

            # Heading for page if multiple pages
            if len(reader.pages) > 1:
                p_head = doc.add_heading(f"Page {page_num}", level=2)
                p_head.paragraph_format.space_before = Pt(12)

            in_list = False
            for line in lines:
                sline = line.strip()
                if not sline:
                    continue

                # Detect bullet lists
                if sline.startswith(('-', '•', '*', '–', '—')) or re.match(r'^\d+[\.\)]\s+', sline):
                    clean_item = re.sub(r'^[•\-\*–—\d\.\)]\s*', '', sline)
                    doc.add_paragraph(clean_item, style='List Bullet')
                    in_list = True
                elif len(sline) < 60 and sline.isupper():
                    doc.add_heading(sline.title(), level=3)
                else:
                    doc.add_paragraph(sline)

        buf = io.BytesIO()
        doc.save(buf)
        return buf.getvalue()

    @staticmethod
    def pdf_to_pptx(pdf_bytes: bytes) -> bytes:
        if not PdfReader:
            raise RuntimeError("pypdf is not installed")
        if not Presentation:
            raise RuntimeError("python-pptx is not installed")

        reader = PdfReader(io.BytesIO(pdf_bytes))
        prs = Presentation()
        # Slide width 10x7.5 inches standard
        blank_slide_layout = prs.slide_layouts[6] if len(prs.slide_layouts) > 6 else prs.slide_layouts[0]

        for page_num, page in enumerate(reader.pages, start=1):
            slide = prs.slides.add_slide(blank_slide_layout)
            text = page.extract_text() or ""
            lines = [l.strip() for l in text.splitlines() if l.strip()]

            # Slide Title Box
            title_box = slide.shapes.add_textbox(PptxInches(0.8), PptxInches(0.5), PptxInches(8.4), PptxInches(1.0))
            tf_title = title_box.text_frame
            tf_title.word_wrap = True
            first_line = lines[0] if lines else f"Page {page_num}"
            p_title = tf_title.paragraphs[0]
            p_title.text = first_line[:80]
            p_title.font.bold = True
            p_title.font.size = PptxPt(22)
            if PptxRGBColor:
                p_title.font.color.rgb = PptxRGBColor(0xCF, 0x4A, 0x0C)

            # Slide Content Box
            content_lines = lines[1:] if len(lines) > 1 else lines
            content_box = slide.shapes.add_textbox(PptxInches(0.8), PptxInches(1.6), PptxInches(8.4), PptxInches(5.0))
            tf_content = content_box.text_frame
            tf_content.word_wrap = True

            for idx, cline in enumerate(content_lines[:15]): # up to 15 key points per slide
                p = tf_content.add_paragraph() if idx > 0 else tf_content.paragraphs[0]
                p.text = cline[:150]
                p.font.size = PptxPt(14)
                p.level = 0

        buf = io.BytesIO()
        prs.save(buf)
        return buf.getvalue()

    @staticmethod
    def pdf_to_xlsx(pdf_bytes: bytes) -> bytes:
        if not PdfReader:
            raise RuntimeError("pypdf is not installed")
        if not openpyxl:
            raise RuntimeError("openpyxl is not installed")

        reader = PdfReader(io.BytesIO(pdf_bytes))
        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "Extracted PDF Data"

        # Styles
        header_fill = PatternFill(start_color="CF4A0C", end_color="CF4A0C", fill_type="solid")
        header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
        regular_font = Font(name="Calibri", size=10)
        thin_border = Border(
            left=Side(style='thin', color='E2E8F0'),
            right=Side(style='thin', color='E2E8F0'),
            top=Side(style='thin', color='E2E8F0'),
            bottom=Side(style='thin', color='E2E8F0')
        )

        ws.cell(row=1, column=1, value="Pixnivo PDF to Excel Structured Table Extraction").font = Font(size=14, bold=True, color="CF4A0C")
        current_row = 3

        for page_num, page in enumerate(reader.pages, start=1):
            text = page.extract_text() or ""
            lines = [l.strip() for l in text.splitlines() if l.strip()]
            if not lines:
                continue

            ws.cell(row=current_row, column=1, value=f"— Page {page_num} —").font = Font(bold=True, italic=True)
            current_row += 1

            for line in lines:
                # Split line by common delimiters: tab, multiple spaces, pipe, comma
                if '\t' in line:
                    cols = [c.strip() for c in line.split('\t')]
                elif ' | ' in line:
                    cols = [c.strip() for c in line.split('|')]
                elif re.search(r'\s{2,}', line):
                    cols = [c.strip() for c in re.split(r'\s{2,}', line)]
                elif ',' in line and len(line.split(',')) > 2:
                    cols = [c.strip() for c in line.split(',')]
                else:
                    cols = [line]

                for col_idx, val in enumerate(cols, start=1):
                    cell = ws.cell(row=current_row, column=col_idx, value=val)
                    cell.font = regular_font
                    cell.border = thin_border
                current_row += 1
            current_row += 1

        # Auto-adjust column widths
        for col in ws.columns:
            max_len = 0
            col_letter = get_column_letter(col[0].column)
            for cell in col:
                val = str(cell.value or '')
                if len(val) > max_len and len(val) < 60:
                    max_len = len(val)
            ws.column_dimensions[col_letter].width = max(max_len + 3, 12)

        buf = io.BytesIO()
        wb.save(buf)
        return buf.getvalue()

    @staticmethod
    def docx_to_pdf(docx_bytes: bytes) -> bytes:
        if not Document or not SimpleDocTemplate:
            raise RuntimeError("python-docx and reportlab are required")

        doc = Document(io.BytesIO(docx_bytes))
        buf = io.BytesIO()
        pdf = SimpleDocTemplate(buf, pagesize=letter, leftMargin=54, rightMargin=54, topMargin=54, bottomMargin=54)
        
        styles = getSampleStyleSheet()
        normal_style = styles['Normal']
        normal_style.fontSize = 10
        normal_style.leading = 14

        h1_style = ParagraphStyle(
            'H1',
            parent=styles['Heading1'],
            fontSize=18,
            leading=22,
            textColor=colors.HexColor('#cf4a0c'),
            spaceAfter=10
        )
        h2_style = ParagraphStyle(
            'H2',
            parent=styles['Heading2'],
            fontSize=14,
            leading=18,
            textColor=colors.HexColor('#1e293b'),
            spaceBefore=12,
            spaceAfter=6
        )

        elements = []

        for p in doc.paragraphs:
            text = p.text.strip()
            if not text:
                elements.append(Spacer(1, 6))
                continue
            
            # Map docx style name
            sname = p.style.name.lower()
            if 'heading 1' in sname:
                elements.append(Paragraph(text, h1_style))
            elif 'heading 2' in sname or 'heading 3' in sname:
                elements.append(Paragraph(text, h2_style))
            elif 'list' in sname or text.startswith(('•', '-', '*')):
                clean = re.sub(r'^[•\-\*]\s*', '', text)
                elements.append(Paragraph(f"&bull; {clean}", normal_style))
            else:
                elements.append(Paragraph(text, normal_style))
                elements.append(Spacer(1, 4))

        # Also parse tables if present
        for t in doc.tables:
            table_data = []
            for row in t.rows:
                row_data = [Paragraph(cell.text.strip(), normal_style) for cell in row.cells]
                table_data.append(row_data)
            if table_data:
                t_flowable = Table(table_data)
                t_flowable.setStyle(TableStyle([
                    ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#F1F5F9')),
                    ('TEXTCOLOR', (0, 0), (-1, -1), colors.black),
                    ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
                    ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                    ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
                    ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
                ]))
                elements.append(Spacer(1, 10))
                elements.append(t_flowable)
                elements.append(Spacer(1, 10))

        if not elements:
            elements.append(Paragraph("Empty Document", normal_style))

        pdf.build(elements)
        return buf.getvalue()

    @staticmethod
    def pptx_to_pdf(pptx_bytes: bytes) -> bytes:
        if not Presentation or not SimpleDocTemplate:
            raise RuntimeError("python-pptx and reportlab are required")

        prs = Presentation(io.BytesIO(pptx_bytes))
        buf = io.BytesIO()
        pdf = SimpleDocTemplate(buf, pagesize=landscape(letter), leftMargin=54, rightMargin=54, topMargin=54, bottomMargin=54)

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            'SlideTitle',
            parent=styles['Heading1'],
            fontSize=22,
            leading=26,
            textColor=colors.HexColor('#cf4a0c'),
            spaceAfter=12
        )
        body_style = ParagraphStyle(
            'SlideBody',
            parent=styles['Normal'],
            fontSize=13,
            leading=18,
            textColor=colors.HexColor('#334155'),
            spaceAfter=8
        )

        elements = []
        for slide_idx, slide in enumerate(prs.slides, start=1):
            if slide_idx > 1:
                elements.append(PageBreak())

            elements.append(Paragraph(f"Slide {slide_idx}", ParagraphStyle('SlideNum', fontSize=9, textColor=colors.HexColor('#94a3b8'))))
            
            # Extract texts
            slide_texts = []
            for shape in slide.shapes:
                if shape.has_text_frame:
                    for paragraph in shape.text_frame.paragraphs:
                        t = paragraph.text.strip()
                        if t:
                            slide_texts.append(t)

            if slide_texts:
                elements.append(Paragraph(slide_texts[0], title_style))
                elements.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#E2E8F0'), spaceAfter=14))
                for line in slide_texts[1:]:
                    elements.append(Paragraph(f"&bull; {line}", body_style))
            else:
                elements.append(Paragraph("Empty Slide", title_style))

        if not elements:
            elements.append(Paragraph("Empty Presentation", title_style))

        pdf.build(elements)
        return buf.getvalue()

    @staticmethod
    def xlsx_to_pdf(xlsx_bytes: bytes) -> bytes:
        if not openpyxl or not SimpleDocTemplate:
            raise RuntimeError("openpyxl and reportlab are required")

        wb = openpyxl.load_workbook(io.BytesIO(xlsx_bytes), data_only=True)
        buf = io.BytesIO()
        pdf = SimpleDocTemplate(buf, pagesize=landscape(letter), leftMargin=36, rightMargin=36, topMargin=36, bottomMargin=36)

        styles = getSampleStyleSheet()
        sheet_style = ParagraphStyle('SheetTitle', fontSize=16, leading=20, textColor=colors.HexColor('#cf4a0c'), spaceAfter=10)
        cell_style = ParagraphStyle('Cell', fontSize=8, leading=10, textColor=colors.black)

        elements = []
        for sheet_idx, sheet in enumerate(wb.worksheets):
            if sheet_idx > 0:
                elements.append(PageBreak())

            elements.append(Paragraph(f"Sheet: {sheet.title}", sheet_style))

            table_data = []
            for row in sheet.iter_rows(values_only=True):
                # Filter rows that have at least one non-empty value
                if any(v is not None and str(v).strip() != '' for v in row):
                    row_data = [Paragraph(str(v) if v is not None else '', cell_style) for v in row[:10]] # limit to 10 cols for width fit
                    table_data.append(row_data)

            if table_data:
                t = Table(table_data)
                t.setStyle(TableStyle([
                    ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#F8FAFC')),
                    ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#0F172A')),
                    ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
                    ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                    ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
                    ('TOPPADDING', (0, 0), (-1, -1), 3),
                    ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
                ]))
                elements.append(t)
            else:
                elements.append(Paragraph("No data found in sheet", cell_style))

        if not elements:
            elements.append(Paragraph("Empty Spreadsheet", sheet_style))

        pdf.build(elements)
        return buf.getvalue()

    @staticmethod
    def pdf_to_markdown(pdf_bytes: bytes) -> str:
        if not PdfReader:
            raise RuntimeError("pypdf is not installed")

        reader = PdfReader(io.BytesIO(pdf_bytes))
        lines_out = ["# Converted Document\n", "*Generated by Pixnivo PDF Tools Suite*\n"]

        for page_num, page in enumerate(reader.pages, start=1):
            text = page.extract_text() or ""
            lines = text.splitlines()
            if not lines:
                continue

            lines_out.append(f"\n## Page {page_num}\n")
            for line in lines:
                sline = line.strip()
                if not sline:
                    continue

                if len(sline) < 40 and sline.isupper():
                    lines_out.append(f"### {sline.title()}\n")
                elif sline.startswith(('•', '-', '*')):
                    clean = re.sub(r'^[•\-\*]\s*', '', sline)
                    lines_out.append(f"- {clean}")
                elif re.match(r'^\d+[\.\)]\s+', sline):
                    lines_out.append(sline)
                else:
                    lines_out.append(f"\n{sline}\n")

        return "\n".join(lines_out)

    @staticmethod
    def html_to_pdf(html_content: str) -> bytes:
        if not SimpleDocTemplate:
            raise RuntimeError("reportlab is required")

        buf = io.BytesIO()
        pdf = SimpleDocTemplate(buf, pagesize=letter, leftMargin=54, rightMargin=54, topMargin=54, bottomMargin=54)
        styles = getSampleStyleSheet()

        h1_style = ParagraphStyle('H1', parent=styles['Heading1'], fontSize=20, leading=24, textColor=colors.HexColor('#cf4a0c'), spaceAfter=12)
        h2_style = ParagraphStyle('H2', parent=styles['Heading2'], fontSize=15, leading=19, textColor=colors.HexColor('#1e293b'), spaceBefore=10, spaceAfter=6)
        body_style = ParagraphStyle('Body', parent=styles['Normal'], fontSize=10, leading=15, spaceAfter=6)

        # Parse basic tags: <h1>, <h2>, <p>, <li>, <br>
        clean_html = re.sub(r'<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>', '', html_content, flags=re.IGNORECASE)
        clean_html = re.sub(r'<style\b[^<]*(?:(?!<\/style>)<[^<]*)*<\/style>', '', clean_html, flags=re.IGNORECASE)

        elements = []
        # Find headers, paragraphs, and list items
        tokens = re.split(r'(<h[1-6][^>]*>.*?</h[1-6]>|<p[^>]*>.*?</p>|<li[^>]*>.*?</li>|<hr\s*/?>)', clean_html, flags=re.IGNORECASE | re.DOTALL)

        for token in tokens:
            t = token.strip()
            if not t:
                continue

            # Strip inner tags for text extraction while allowing safe tags like <b>, <i>
            content = re.sub(r'<(?!\/?(b|i|strong|em)\b)[^>]+>', '', t).strip()
            content = re.sub(r'&nbsp;', ' ', content)
            if not content:
                continue

            if re.match(r'<h1', t, re.IGNORECASE):
                elements.append(Paragraph(content, h1_style))
            elif re.match(r'<h[2-6]', t, re.IGNORECASE):
                elements.append(Paragraph(content, h2_style))
            elif re.match(r'<li', t, re.IGNORECASE):
                elements.append(Paragraph(f"&bull; {content}", body_style))
            elif re.match(r'<hr', t, re.IGNORECASE):
                elements.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#CBD5E1'), spaceAfter=8))
            else:
                elements.append(Paragraph(content, body_style))

        if not elements:
            # Fallback to plain text
            plain = re.sub(r'<[^>]+>', ' ', clean_html)
            elements.append(Paragraph(plain[:2000], body_style))

        pdf.build(elements)
        return buf.getvalue()
