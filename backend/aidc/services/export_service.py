"""
AIDC Export Service
Generates professional PDF catalogs, Avery label sheets, Word (.docx), Excel (.xlsx), and ZIP archives.
"""
from typing import List, Dict, Any, Optional
from io import BytesIO
import base64
import zipfile
import csv

from reportlab.pdfgen import canvas
from reportlab.lib.pagesizes import letter
from reportlab.lib.utils import ImageReader
from reportlab.graphics import renderPDF
from PIL import Image

try:
    from docx import Document
    from docx.shared import Inches, Pt, RGBColor
except ImportError:
    Document = None

try:
    import openpyxl
    from openpyxl.drawing.image import Image as OpenpyxlImage
    from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
except ImportError:
    openpyxl = None

from ..schemas import BarcodeExportItem, ExportRequest
from .render_service import RenderService

class ExportService:
    @classmethod
    def export_pdf_catalog(cls, items: List[BarcodeExportItem], title: str = "AIDC Studio Barcode Catalog") -> bytes:
        """
        Creates a clean, multi-page vector PDF catalog with 4-6 barcodes per page,
        headers, metadata, and page numbers.
        """
        buf = BytesIO()
        c = canvas.Canvas(buf, pagesize=letter)
        page_w, page_h = letter
        
        y_margin = 50
        x_margin = 54
        usable_w = page_w - (2 * x_margin)
        y_pos = page_h - y_margin

        def draw_header(pg_num: int):
            c.setFont("Helvetica-Bold", 16)
            c.setFillColorRGB(0.81, 0.29, 0.05) # Pixnivo brand orange
            c.drawString(x_margin, page_h - 40, "PIXNIVO AIDC STUDIO")
            c.setFont("Helvetica", 11)
            c.setFillColorRGB(0.3, 0.3, 0.3)
            c.drawString(x_margin + 200, page_h - 40, f"— {title}")
            c.setStrokeColorRGB(0.85, 0.85, 0.85)
            c.setLineWidth(1)
            c.line(x_margin, page_h - 48, page_w - x_margin, page_h - 48)

            # Footer
            c.setFont("Helvetica", 9)
            c.setFillColorRGB(0.5, 0.5, 0.5)
            c.drawString(x_margin, 30, "Generated by Pixnivo AIDC Studio (https://pixnivo.app)")
            c.drawRightString(page_w - x_margin, 30, f"Page {pg_num}")

        page_count = 1
        draw_header(page_count)
        y_pos = page_h - 75

        for idx, item in enumerate(items):
            item_h = 105
            if y_pos - item_h < 50:
                c.showPage()
                page_count += 1
                draw_header(page_count)
                y_pos = page_h - 75

            # Item card border
            c.setStrokeColorRGB(0.9, 0.9, 0.92)
            c.setFillColorRGB(0.98, 0.98, 0.99)
            c.roundRect(x_margin, y_pos - item_h + 10, usable_w, item_h - 10, 6, stroke=1, fill=1)

            # Meta texts
            c.setFont("Helvetica-Bold", 11)
            c.setFillColorRGB(0.1, 0.1, 0.1)
            label = item.title or f"Asset #{idx + 1}"
            c.drawString(x_margin + 15, y_pos - 20, label)

            c.setFont("Helvetica", 9)
            c.setFillColorRGB(0.4, 0.4, 0.4)
            c.drawString(x_margin + 15, y_pos - 35, f"Symbology: {item.symbology or 'Code 128'}")
            if item.sku:
                c.drawString(x_margin + 15, y_pos - 48, f"SKU: {item.sku}")

            c.setFont("Courier-Bold", 9)
            c.setFillColorRGB(0.1, 0.1, 0.1)
            c.drawString(x_margin + 15, y_pos - 70, f"Data: {item.text[:48]}")

            # Draw barcode
            barcode_x = x_margin + usable_w - 240
            barcode_y = y_pos - item_h + 18

            if item.base64_data:
                try:
                    b64_clean = item.base64_data.split(',')[-1]
                    img_data = base64.b64decode(b64_clean)
                    img_stream = BytesIO(img_data)
                    pil_img = Image.open(img_stream)
                    iw, ih = pil_img.size
                    target_w = min(220, iw)
                    target_h = ih * (target_w / iw)
                    target_h = min(item_h - 25, target_h)
                    img_stream.seek(0)
                    rl_img = ImageReader(img_stream)
                    c.drawImage(rl_img, barcode_x, barcode_y, width=target_w, height=target_h)
                except Exception:
                    pass
            else:
                try:
                    drawing = RenderService.create_drawing(item.symbology or "code128", item.text)
                    renderPDF.draw(drawing, c, barcode_x, barcode_y)
                except Exception:
                    c.setFont("Helvetica-Oblique", 9)
                    c.drawString(barcode_x, barcode_y + 20, "[Barcode Drawing]")

            y_pos -= item_h

        c.save()
        return buf.getvalue()

    @classmethod
    def export_docx(cls, items: List[BarcodeExportItem], title: str = "Generated Barcodes") -> bytes:
        """
        Creates a formatted Microsoft Word (.docx) document with a 3-column table
        containing metadata, payload, and the barcode image.
        """
        if Document is None:
            raise RuntimeError("python-docx is not installed.")

        doc = Document()
        title_p = doc.add_heading(title, 0)
        p = doc.add_paragraph("Exported from Pixnivo AIDC Studio (https://pixnivo.app)")
        p.runs[0].font.size = Pt(9)
        p.runs[0].font.color.rgb = RGBColor(120, 120, 120)

        table = doc.add_table(rows=1, cols=3)
        table.autofit = True
        hdr_cells = table.rows[0].cells
        hdr_cells[0].text = "Item & SKU"
        hdr_cells[1].text = "Payload (Data)"
        hdr_cells[2].text = "Barcode Asset"

        for item in items:
            row_cells = table.add_row().cells
            row_cells[0].text = f"{item.title or 'Item'}\nSKU: {item.sku or '—'}"
            row_cells[1].text = item.text

            if item.base64_data:
                try:
                    b64_clean = item.base64_data.split(',')[-1]
                    img_data = base64.b64decode(b64_clean)
                    img_stream = BytesIO(img_data)
                    p_img = row_cells[2].paragraphs[0]
                    r_img = p_img.add_run()
                    r_img.add_picture(img_stream, width=Inches(2.2))
                except Exception:
                    row_cells[2].text = "[Image Preview]"
            else:
                row_cells[2].text = f"[{item.symbology or 'Code 128'}]"

        out = BytesIO()
        doc.save(out)
        return out.getvalue()

    @classmethod
    def export_xlsx(cls, items: List[BarcodeExportItem]) -> bytes:
        """
        Creates an Excel (.xlsx) workbook with styled header cells and embedded barcodes.
        """
        if openpyxl is None:
            raise RuntimeError("openpyxl is not installed.")

        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "AIDC Barcodes"

        headers = ["Index", "Title / Name", "SKU", "Symbology", "Payload", "Barcode Graphic"]
        for col_idx, h in enumerate(headers, 1):
            cell = ws.cell(row=1, column=col_idx, value=h)
            cell.font = Font(bold=True, color="FFFFFF")
            cell.fill = PatternFill(start_color="CF4A0C", end_color="CF4A0C", fill_type="solid")
            cell.alignment = Alignment(horizontal="center", vertical="center")

        ws.column_dimensions['A'].width = 8
        ws.column_dimensions['B'].width = 24
        ws.column_dimensions['C'].width = 16
        ws.column_dimensions['D'].width = 16
        ws.column_dimensions['E'].width = 32
        ws.column_dimensions['F'].width = 36

        for idx, item in enumerate(items, start=2):
            ws.cell(row=idx, column=1, value=idx - 1)
            ws.cell(row=idx, column=2, value=item.title or f"Asset #{idx - 1}")
            ws.cell(row=idx, column=3, value=item.sku or "")
            ws.cell(row=idx, column=4, value=item.symbology or "code128")
            ws.cell(row=idx, column=5, value=item.text)

            if item.base64_data:
                try:
                    b64_clean = item.base64_data.split(',')[-1]
                    img_data = base64.b64decode(b64_clean)
                    img_stream = BytesIO(img_data)
                    img = OpenpyxlImage(img_stream)
                    # Resize proportionally to fit row
                    target_w = 160
                    aspect = img.height / img.width if img.width else 0.5
                    img.width = target_w
                    img.height = int(target_w * aspect)
                    ws.add_image(img, f"F{idx}")
                    ws.row_dimensions[idx].height = max(45, int(img.height * 0.75))
                except Exception:
                    pass
            else:
                ws.row_dimensions[idx].height = 25

        out = BytesIO()
        wb.save(out)
        return out.getvalue()

    @classmethod
    def export_zip(cls, items: List[BarcodeExportItem]) -> bytes:
        """
        Creates a ZIP archive with individual PNG files and a manifest CSV log.
        """
        import io
        zip_buf = BytesIO()
        with zipfile.ZipFile(zip_buf, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
            # Manifest log
            csv_buf = io.StringIO()
            writer = csv.writer(csv_buf)
            writer.writerow(["Filename", "Title", "SKU", "Symbology", "Payload"])

            for idx, item in enumerate(items, start=1):
                clean_name = f"barcode_{idx:04d}_{item.sku or 'item'}.png".replace(" ", "_")
                writer.writerow([clean_name, item.title or "", item.sku or "", item.symbology or "", item.text])

                if item.base64_data:
                    try:
                        b64_clean = item.base64_data.split(',')[-1]
                        raw_png = base64.b64decode(b64_clean)
                        zf.writestr(f"barcodes/{clean_name}", raw_png)
                    except Exception:
                        pass

            zf.writestr("manifest.csv", csv_buf.getvalue())

        return zip_buf.getvalue()
